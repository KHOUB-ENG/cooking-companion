// Which recipes actually have a photo?
//
// Without this the app renders an <img> for every recipe and lets the browser
// fail on the missing ones - but a missing file doesn't 404, it serves the SPA's
// index.html with a 200, so each one downloads a whole web page before erroring.
// A build-time manifest means we only ever request photos that exist.
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'fs'

const DIR = 'public/recipes'
if (!existsSync(DIR)) mkdirSync(DIR, { recursive: true })

const ids = readdirSync(DIR)
  .filter(f => f.endsWith('.jpg'))
  .map(f => f.slice(0, -4))
  .sort()

writeFileSync('src/data/photos.ts', `// GENERATED by scripts/photo-manifest.mjs - do not edit by hand.
// Run \`npm run photos\` after adding images to public/recipes.

/** Recipe ids with a photo on disk. Everything else shows its emoji card. */
export const HAS_PHOTO = new Set<string>([
${ids.map(i => `  '${i}',`).join('\n')}
])
`)
console.log(`photo manifest: ${ids.length} recipes have a photo`)
